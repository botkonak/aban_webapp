def page_index(note: str = "") -> Page:
    prefix = f"{note}\n\n" if note else ""
    text = (
        f"{prefix}<b>راهنمای ربات</b>\n\n"
        "یکی از عنوان‌های زیر رو انتخاب کن تا راهنمای همون بخش رو ببینی.\n"
    )
    rows = [
        [btn(HELP_SECTIONS[k][0], f"u:hlt:{k}") for k in row] for row in INDEX_ROWS
    ]
    rows.append(back_row("u:menu"))
    return text, kb(*rows)


def page_section(key: str = "", note: str = "") -> Page:
    item = HELP_SECTIONS.get(key)
    if item is None:
        return page_index("❌ این بخش پیدا نشد.")
    title, body = item
    prefix = f"{note}\n\n" if note else ""
    text = f"{prefix}<b>{title}</b>\n\n{body}"
    return text, kb(back_row("u:hl"))